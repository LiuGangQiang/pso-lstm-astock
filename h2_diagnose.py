# -*- coding: utf-8 -*-
"""H2 Bias Decomposition Diagnosis: Fitness Variance of Structural Marginals vs. Weight Marginals (Chapter 3, H2 of the Proposal Document).

For the gbest particle of Unified-PSO:
  - Structural marginal: Fix the gbest weight segment, randomly change K structures (seq_len, hidden), and calculate the fitness std;
  - Weight marginal: Fix the gbest structure, replace K sets of Glorot/orthogonal initialization weights, and calculate the fitness std.
If the weight marginalal std >> the structural marginal std, then H2 holds (the structure signal is drowned out by the weight segment).

Usage: python h2_diagnose.py"""
import numpy as np
import torch

from pso_lstm import (LSTMRegressor, UNI_HIDDEN, UNI_SEQ_BOUNDS, _weight_dim,
                      decode_struct, eval_mse, init_weights_paper12,
                      make_sequences, unified_pso_search)
from run_m1_baseline import prepare_fold
from run_s2 import SUBSAMPLE, WEIGHT_PENALTY
from select_stocks import CANDIDATES

STOCKS = ["600036", "600276", "300750", "300308"]
HORIZON = 10
FOLD, SEEDS, K = 0, [0, 1, 2], 20


def uni_fitness(vec, cache, train_s, horizon, seed):
    """Fitness that is completely consistent with unified_pso_search (subsampling fixed by seed + full-segment penalty).

    V3.5 Revision (Review Annotation c5): Structural decoding aligned with decode_struct in unified_pso_search
    Coordinate mapping (the old version used coordinates directly as seq_len/hidden, which belongs to the old decoding semantics of V2 and earlier versions)."""
    seq_len, hidden = decode_struct(vec[0], vec[1], UNI_SEQ_BOUNDS, UNI_HIDDEN)
    if seq_len not in cache:
        x, y = make_sequences(train_s, seq_len, horizon)
        if SUBSAMPLE and len(x) > SUBSAMPLE:
            idx = np.random.RandomState(seed).choice(len(x), SUBSAMPLE, replace=False)
            x, y = x[idx], y[idx]
        cache[seq_len] = (x, y)
    x, y = cache[seq_len]
    m = LSTMRegressor(hidden=hidden)
    m.set_vector(vec[2:2 + m.get_vector().size])
    mse = eval_mse(m, x, y)
    return mse + WEIGHT_PENALTY * float(np.mean(vec[2:] ** 2))


def main():
    import argparse, sys
    ap = argparse.ArgumentParser()
    ap.add_argument("--stock", default=None)
    ap.add_argument("--seed", type=int, default=None)
    args = ap.parse_args()
    stocks = [args.stock] if args.stock else STOCKS
    seeds = [args.seed] if args.seed is not None else SEEDS

    torch.set_num_threads(1)
    rng = np.random.default_rng(7)
    print(f"{'stock':<8}{'seed':<4}{'gbest structure':<10}{'Structure-marginal std':<12}{'Weight-marginal std':<12}{'Ratio (weight/structure)'}")
    for code in stocks:
        from run_m1_baseline import load_series
        close = load_series(code)
        train_s, *_ = prepare_fold(close, 20, HORIZON, FOLD)
        for seed in seeds:
            gbest, fit, _, decode = unified_pso_search(
                train_s, n_particles=15, iters=20, seed=seed, horizon=HORIZON,
                weight_penalty=WEIGHT_PENALTY, fitness_subsample=SUBSAMPLE)
            s, h = decode(gbest)
            cache = {}
            # Structural margin: Weight range remains unchanged, random structure
            struct_fits = []
            for _ in range(K):
                v = gbest.copy()
                # Uniform sampling of structural coordinates within [-5, 5] (the complete reachable domain of decode_struct)
                v[0] = rng.uniform(-5, 5)
                v[1] = rng.uniform(-5, 5)
                struct_fits.append(uni_fitness(v, cache, train_s, HORIZON, seed))
            # Weight marginal: Structure remains unchanged, random Glorot weights (generated by h64 and then truncated)
            weight_fits = []
            for k in range(K):
                v = gbest.copy()
                probe = LSTMRegressor(hidden=int(UNI_HIDDEN.max()))
                init_weights_paper12(probe, n_features=1, seed=seed * 1000 + 100 + k)
                v[2:] = probe.get_vector()
                weight_fits.append(uni_fitness(v, cache, train_s, HORIZON, seed))
            ss, sw = np.std(struct_fits), np.std(weight_fits)
            print(f"{CANDIDATES[code][0]:<8}{seed:<4}s{s},h{h:<6}"
                  f"{ss:<12.5f}{sw:<12.5f}{sw / (ss + 1e-12):.2f}")


if __name__ == "__main__":
    main()
